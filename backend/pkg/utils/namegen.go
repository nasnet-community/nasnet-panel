// CaseFormat selects how the generated name parts are cased.
type CaseFormat string

// Supported case formats for GenerateName.
const (
	CamelCase  CaseFormat = "cc" // first part lowercase, the rest Capitalized
	PascalCase CaseFormat = "pc" // every part Capitalized
	LowerCase  CaseFormat = "lc" // every part lowercase
)

// capitalize returns the part with its first letter upper-cased and the
// rest lower-cased. Parts only contain a-z/A-Z, so byte indexing is safe.
func capitalize(part string) string {
	if part == "" {
		return part
	}
	lower := strings.ToLower(part)
	return strings.ToUpper(lower[:1]) + lower[1:]
}

// formatPart applies the case format to a single part; first marks the
// first part of the name. Unknown formats leave the part unchanged.
func formatPart(part string, format CaseFormat, first bool) string {
	switch format {
	case LowerCase:
		return strings.ToLower(part)
	case CamelCase:
		if first {
			return strings.ToLower(part)
		}
		return capitalize(part)
	case PascalCase:
		return capitalize(part)
	}
	return part
}

// randomPartIndex returns a random index into nameParts using crypto/rand.
func randomPartIndex() int {
	idx, err := rand.Int(rand.Reader, big.NewInt(int64(len(nameParts))))
	if err != nil {
		return 0
	}
	return int(idx.Int64())
}

// GenerateName builds a random name with the given number of parts joined
// by sep, picking each part randomly from nameParts and casing it
// according to format (CamelCase, PascalCase or LowerCase).
func GenerateName(parts int, sep string, format CaseFormat) string {
	picked := make([]string, parts)
	for i := range picked {
		picked[i] = formatPart(nameParts[randomPartIndex()], format, i == 0)
	}
	return strings.Join(picked, sep)
}
