package routes

import (
	"nasnet-panel/internal/handler/app"
	"nasnet-panel/internal/handler/config"
	"nasnet-panel/internal/handler/dhcp"
	"nasnet-panel/internal/handler/diag"
	"nasnet-panel/internal/handler/dns"
	"nasnet-panel/internal/handler/firewall"
	"nasnet-panel/internal/handler/health"
	"nasnet-panel/internal/handler/iface"
	"nasnet-panel/internal/handler/logs"
	"nasnet-panel/internal/handler/net"
	"nasnet-panel/internal/handler/plugin"
	"nasnet-panel/internal/handler/route"
	"nasnet-panel/internal/handler/scan"
	"nasnet-panel/internal/handler/system"
	"nasnet-panel/internal/handler/vpn"
	"nasnet-panel/internal/handler/wifi"
	"nasnet-panel/internal/middleware"

	"github.com/labstack/echo/v4"
)

// RegisterRoutes registers all API routes.
func RegisterRoutes(e *echo.Echo) {
	e.GET("/health", health.HandleHealthCheck)
	initSwagger(e)

	appGroup := e.Group("/api/app")
	appGroup.Use(middleware.RouterOSAuth)
	appGroup.GET("/settings", app.HandleListSettings)
	appGroup.POST("/newsletter", app.HandleAppNewsletter)
	appGroup.POST("/settings", app.HandleCreateSetting)
	appGroup.GET("/settings/:key", app.HandleGetSetting)
	appGroup.PUT("/settings/:key", app.HandleUpdateSetting)
	appGroup.DELETE("/settings/:key", app.HandleDeleteSetting)
	appGroup.POST("/update", app.HandleAppUpdate)
	appGroup.GET("/update/channel", app.HandleAppUpdateChannel)
	appGroup.GET("/update/status", app.HandleAppUpdateProgress)
	appGroup.GET("/update/:tag", app.HandleAppUpdateRelease)
	appGroup.GET("/updates", app.HandleAppUpdates)
	appGroup.GET("/version", app.HandleAppVersion)

	configGroup := e.Group("/api/config")
	configGroup.Use(middleware.RouterOSAuth)
	configGroup.POST("/reconfig", config.HandleStartReconfig)
	configGroup.GET("/reconfig/status", config.HandleGetReconfigStatus)
	configGroup.POST("/vpn", config.HandleGetVPNCredentials)
	configGroup.POST("/wizard/finalize", config.HandleFinalizeWizard)
	configGroup.GET("/wizard/status", config.HandleGetWizardStatus)

	dhcpGroup := e.Group("/api/dhcp")
	dhcpGroup.Use(middleware.RouterOSAuth)
	dhcpGroup.POST("/client/:nameOrID", dhcp.HandleConfigureDHCPClient)
	dhcpGroup.GET("/clients", dhcp.HandleListDHCPClients)
	dhcpGroup.GET("/leases", dhcp.HandleListDHCPLeases)
	dhcpGroup.POST("/leases/make-static", dhcp.HandleMakeDHCPLeaseStatic)
	dhcpGroup.DELETE("/leases/:macAddress", dhcp.HandleRemoveDHCPLease)
	dhcpGroup.GET("/servers", dhcp.HandleListDHCPServers)

	diagGroup := e.Group("/api/diag")
	diagGroup.Use(middleware.RouterOSAuth)
	diagGroup.GET("/download", diag.HandleDownloadDiag)
	diagGroup.DELETE("/file", diag.HandleDeleteDiagFile)
	diagGroup.POST("/generate", diag.HandleGenerateDiag)
	diagGroup.GET("/status", diag.HandleGetDiagStatus)

	dnsGroup := e.Group("/api/dns")
	dnsGroup.Use(middleware.RouterOSAuth)
	dnsGroup.POST("/adblock", dns.HandleSetAdBlock)
	dnsGroup.DELETE("/cache", dns.HandleFlushDNSCache)
	dnsGroup.POST("/change", dns.HandleChangeDNS)
	dnsGroup.POST("/family", dns.HandleSetFamilyDNS)
	dnsGroup.GET("/info", dns.HandleGetDNSInfo)
	dnsGroup.PUT("/info", dns.HandleUpdateDNS)
	dnsGroup.GET("/list", dns.HandleListDNSForwarders)
	dnsGroup.POST("/reset", dns.HandleResetDNS)
	dnsGroup.GET("/static", dns.HandleListStaticDNS)
	dnsGroup.POST("/static", dns.HandleCreateStaticDNS)
	dnsGroup.GET("/static/:nameOrID", dns.HandleGetStaticDNS)
	dnsGroup.PUT("/static/:nameOrID", dns.HandleUpdateStaticDNS)
	dnsGroup.DELETE("/static/:nameOrID", dns.HandleDeleteStaticDNS)
	dnsGroup.GET("/suggest", dns.HandleSuggestDNS)
	dnsGroup.GET("/validate", dns.HandleValidateDNS)

	firewallGroup := e.Group("/api/firewall")
	firewallGroup.Use(middleware.RouterOSAuth)
	firewallGroup.GET("/addresslist/domestic", firewall.HandleListDomesticAddresses)
	firewallGroup.POST("/addresslist/domestic", firewall.HandleAddDomesticAddress)
	firewallGroup.GET("/addresslist/domestic/info", firewall.HandleGetDomesticAddressListInfo)
	firewallGroup.POST("/addresslist/domestic/update", firewall.HandleUpdateDomesticAddressList)
	firewallGroup.GET("/addresslist/domestic/update/status", firewall.HandleGetDomesticAddressListUpdateStatus)
	firewallGroup.PUT("/addresslist/domestic/:id", firewall.HandleUpdateDomesticAddress)
	firewallGroup.DELETE("/addresslist/domestic/:id", firewall.HandleDeleteDomesticAddress)
	firewallGroup.GET("/domestic", firewall.HandleGetDomesticBlock)
	firewallGroup.PUT("/domestic", firewall.HandleSetDomesticBlock)
	firewallGroup.GET("/filter", firewall.HandleListFirewallFilterRules)

	interfaceGroup := e.Group("/api/interface")
	interfaceGroup.Use(middleware.RouterOSAuth)
	interfaceGroup.PUT("/bridge/port", iface.HandleUpdateInterfaceBridge)
	interfaceGroup.GET("/bridge/ports", iface.HandleListBridgePorts)
	interfaceGroup.GET("/bridges", iface.HandleListBridges)
	interfaceGroup.POST("/ethernet/cable-test/:nameOrID", iface.HandleTestEthernetCable)
	interfaceGroup.GET("/ethernet/:nameOrID", iface.HandleGetEthernetInterface)
	interfaceGroup.GET("/ethernets", iface.HandleGetEthernetInterfaces)
	interfaceGroup.GET("/graph/:nameOrID", iface.HandleGetInterfaceGraph)
	interfaceGroup.GET("/interfaces", iface.HandleListInterfaces)
	interfaceGroup.DELETE("/traffic-counter/:nameOrID", iface.HandleResetInterfaceTrafficCounter)
	interfaceGroup.PUT("/wan", iface.HandleUpdateWANInterface)
	interfaceGroup.GET("/wan/:name", iface.HandleGetWAN)
	interfaceGroup.GET("/wans", iface.HandleListWANs)

	logsGroup := e.Group("/api/logs")
	logsGroup.Use(middleware.RouterOSAuth)
	logsGroup.GET("", logs.HandleGetLogs)

	netGroup := e.Group("/api/net")
	netGroup.Use(middleware.RouterOSAuth)
	netGroup.GET("/status", net.HandleGetNetStatus)

	// Registered directly on e, not pluginGroup, so it skips RouterOSAuth: this
	// endpoint proxies a plugin's own web UI and doesn't touch RouterOS itself.
	// The base path and the wildcard below it (assets, API calls the plugin's
	// UI makes, etc.) both route here so the whole UI works, not just its
	// landing page.
	e.Any("/api/plugin/view/:pluginID", plugin.HandleViewPlugin)
	e.Any("/api/plugin/view/:pluginID/*", plugin.HandleViewPlugin)

	pluginGroup := e.Group("/api/plugin")
	pluginGroup.Use(middleware.RouterOSAuth)
	pluginGroup.PUT("/env/:pluginId", plugin.HandleSetPluginEnvVar)
	pluginGroup.GET("/envs/:pluginId", plugin.HandleListPluginEnvVars)
	pluginGroup.POST("/install", plugin.HandleInstallPlugin)
	pluginGroup.GET("/install/status/:pluginId", plugin.HandleGetPluginInstallStatus)
	pluginGroup.GET("/installed", plugin.HandleListInstalledPlugins)
	pluginGroup.DELETE("/plugin/:name", plugin.HandleUninstallPlugin)
	pluginGroup.GET("/plugins", plugin.HandleListPlugins)
	pluginGroup.GET("/update/status/:pluginId", plugin.HandleGetPluginUpdateStatus)
	pluginGroup.POST("/update/:pluginId", plugin.HandleUpdatePlugin)

	routeGroup := e.Group("/api/route")
	routeGroup.Use(middleware.RouterOSAuth)
	routeGroup.GET("/foreign-gateway", route.HandleGetForeignGateway)
	routeGroup.PUT("/foreign-gateway", route.HandleUpdateForeignGateway)

	scanGroup := e.Group("/api/scan")
	scanGroup.POST("", scan.HandleStartScan)
	scanGroup.POST("/auto", scan.HandleAutoScan)
	scanGroup.GET("/status/:taskId", scan.HandleScanStatus)
	scanGroup.POST("/stop", scan.HandleStopScan)
	scanGroup.POST("/verify", scan.HandleVerifyIP)

	systemGroup := e.Group("/api/system")
	systemGroup.Use(middleware.RouterOSAuth)
	systemGroup.POST("/backup", system.HandleCreateBackup)
	systemGroup.GET("/backup/download/:filename", system.HandleDownloadBackup)
	systemGroup.DELETE("/backup/:filename", system.HandleDeleteBackup)
	systemGroup.GET("/backups", system.HandleListBackups)
	systemGroup.GET("/check-for-updates", system.HandleCheckForUpdates)
	systemGroup.GET("/identity", system.HandleGetSystemIdentity)
	systemGroup.PUT("/identity", system.HandleSetSystemIdentity)
	systemGroup.GET("/info", system.HandleGetSystemInfo)
	systemGroup.POST("/install-update", system.HandleInstallUpdate)
	systemGroup.PUT("/password", system.HandleChangeUserPassword)
	systemGroup.POST("/reboot", system.HandleRebootSystem)
	systemGroup.GET("/resources", system.HandleGetResourceInfo)
	systemGroup.POST("/restore", system.HandleRestoreBackup)
	systemGroup.GET("/scheduler/:name", system.HandleGetScheduler)
	systemGroup.PUT("/scheduler/:name", system.HandleUpdateScheduler)
	systemGroup.PUT("/service/:nameOrID", system.HandleUpdateIPService)
	systemGroup.GET("/services", system.HandleListIPServices)
	systemGroup.POST("/shutdown", system.HandleShutdownSystem)
	systemGroup.GET("/update-status", system.HandleGetSystemUpdateStatus)
	systemGroup.GET("/updates", system.HandleGetSystemUpdates)

	vpnGroup := e.Group("/api/vpn")
	vpnGroup.Use(middleware.RouterOSAuth)
	vpnGroup.GET("/active", vpn.HandleListActiveVPNConnections)
	vpnGroup.DELETE("/active/:id", vpn.HandleRemovePPPActiveSession)
	vpnGroup.GET("/clients", vpn.HandleListVPNClients)
	vpnGroup.GET("/clients/:name", vpn.HandleGetVPNClient)
	vpnGroup.PUT("/clients/:name", vpn.HandleUpdateVPNClient)
	vpnGroup.POST("/l2tp/client", vpn.HandleAddL2TPClient)
	vpnGroup.GET("/l2tp/client/:name", vpn.HandleGetL2TPClient)
	vpnGroup.PUT("/l2tp/client/:nameOrID", vpn.HandleUpdateL2TPClient)
	vpnGroup.DELETE("/l2tp/client/:nameOrID", vpn.HandleDeleteL2TPClient)
	vpnGroup.GET("/l2tp/server", vpn.HandleGetL2tpServerDetails)
	vpnGroup.POST("/l2tp/server", vpn.HandleCreateL2tpServer)
	vpnGroup.DELETE("/l2tp/server", vpn.HandleDeleteL2tpServer)
	vpnGroup.POST("/ovpn/server", vpn.HandleCreateOvpnServer)
	vpnGroup.GET("/ovpn/server/export", vpn.HandleExportOvpnClient)
	vpnGroup.GET("/ovpn/server/status/:taskId", vpn.HandleGetOvpnServerTaskStatus)
	vpnGroup.GET("/ovpn/server/:name", vpn.HandleGetOvpnServerDetails)
	vpnGroup.PUT("/ovpn/server/:name", vpn.HandleUpdateOvpnServerEnabled)
	vpnGroup.DELETE("/ovpn/server/:name", vpn.HandleDeleteOvpnServer)
	vpnGroup.GET("/pptp/server", vpn.HandleGetPptpServerDetails)
	vpnGroup.GET("/profiles", vpn.HandleListVPNProfiles)
	vpnGroup.GET("/servers", vpn.HandleListVPNServers)
	vpnGroup.POST("/sstp/client", vpn.HandleAddSSTPClient)
	vpnGroup.GET("/sstp/client/:name", vpn.HandleGetSSTPClient)
	vpnGroup.PUT("/sstp/client/:nameOrID", vpn.HandleUpdateSSTPClient)
	vpnGroup.DELETE("/sstp/client/:nameOrID", vpn.HandleDeleteSSTPClient)
	vpnGroup.GET("/sstp/server", vpn.HandleGetSstpServerDetails)
	vpnGroup.POST("/sstp/server", vpn.HandleCreateSstpServer)
	vpnGroup.DELETE("/sstp/server", vpn.HandleDeleteSstpServer)
	vpnGroup.GET("/sstp/server/status/:taskId", vpn.HandleGetSstpServerTaskStatus)
	vpnGroup.GET("/users", vpn.HandleListVPNUsers)
	vpnGroup.POST("/users", vpn.HandleCreateVPNUser)
	vpnGroup.PUT("/users/:nameOrID", vpn.HandleUpdateVPNUserByID)
	vpnGroup.DELETE("/users/:nameOrID", vpn.HandleDeleteVPNUserByID)
	vpnGroup.POST("/wireguard/client", vpn.HandleCreateWireGuardClient)
	vpnGroup.GET("/wireguard/detailed/:name", vpn.HandleGetWireGuardDetailed)
	vpnGroup.POST("/wireguard/import-config", vpn.HandleImportWireGuardConfig)
	vpnGroup.GET("/wireguard/interface/:nameOrID", vpn.HandleGetWireGuardInterface)
	vpnGroup.PUT("/wireguard/interface/:nameOrID", vpn.HandleUpdateWireGuardInterface)
	vpnGroup.DELETE("/wireguard/interface/:nameOrID", vpn.HandleDeleteWireGuardInterface)
	vpnGroup.POST("/wireguard/peer", vpn.HandleCreateWireGuardServerPeer)
	vpnGroup.GET("/wireguard/peer/export", vpn.HandleExportWireGuardPeerConfig)
	vpnGroup.PUT("/wireguard/peer/:nameOrID", vpn.HandleUpdateWireGuardPeer)
	vpnGroup.DELETE("/wireguard/peer/:nameOrID", vpn.HandleDeleteWireGuardPeer)
	vpnGroup.GET("/wireguard/peers/:name", vpn.HandleGetWireGuardPeers)
	vpnGroup.POST("/wireguard/server", vpn.HandleCreateWireGuardServer)

	wifiGroup := e.Group("/api/wifi")
	wifiGroup.Use(middleware.RouterOSAuth)
	wifiGroup.GET("/clients", wifi.HandleListWiFiConnectedClients)
	wifiGroup.DELETE("/clients/:mac", wifi.HandleRemoveWiFiConnectedClient)
	wifiGroup.POST("/connect/:nameOrID", wifi.HandleConnectWiFi)
	wifiGroup.GET("/interfaces", wifi.HandleListWiFiInterfaces)
	wifiGroup.GET("/interfaces/:name", wifi.HandleGetWiFiInterface)
	wifiGroup.PUT("/interfaces/:name", wifi.HandleUpdateWiFiInterface)
	wifiGroup.GET("/passphrase/:name", wifi.HandleGetWiFiPassphrase)
	wifiGroup.PUT("/passphrase/:name", wifi.HandleChangeWiFiPassphrase)
	wifiGroup.GET("/scan/:nameOrID", wifi.HandleScanWiFiAccessPoints)
	wifiGroup.PUT("/settings/:name", wifi.HandleUpdateWiFiSettings)
	wifiGroup.GET("/status/:nameOrID", wifi.HandleGetWiFiStatus)
	wifiGroup.POST("/virtual", wifi.HandleCreateVirtualWiFiInterface)
	wifiGroup.DELETE("/virtual/:nameOrID", wifi.HandleDeleteVirtualWiFiInterface)
}
